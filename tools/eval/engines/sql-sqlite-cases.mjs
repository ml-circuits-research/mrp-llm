#!/usr/bin/env node
/**
 * Writes the smoke cases 50 to 54 of `sql-sqlite` (eval/smoke-reasoning/cases/): bulk relational work on thousands of generated facts, the
 * strength of a set-at-a-time engine. Every expected answer is computed here PROCEDURALLY from the generator's own data (no strategy is
 * called), then checked against js-oracle by the harness and the tests.
 *
 *   node tools/eval/engines/sql-sqlite-cases.mjs          write the five case folders
 *   node tools/eval/engines/sql-sqlite-cases.mjs --check  fail when the files on disk differ from the generator
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const casesRoot = path.resolve(here, '../../../eval/smoke-reasoning/cases');
const fact = (i, text) => `@f${i} fact\n  holds ${text}\n`;
const pred = (name, args, closed = false) => `@${name} predicate\n  args ${args}\n${closed ? '  closed true\n' : ''}`;
const json = x => JSON.stringify(x, null, 2) + '\n';

function bulkJoin() {
  const O = 3000, C = 150, R = 12;
  const cust = o => (o * 7 + 3) % C, region = c => c % R, zone = r => r % 4;
  const facts = [];
  for (let o = 0; o < O; o++) facts.push(`orders o${o} c${cust(o)}`);
  for (let c = 0; c < C; c++) facts.push(`lives c${c} g${region(c)}`);
  for (let r = 0; r < R; r++) facts.push(`zone_of g${r} z${zone(r)}`);
  const knowledge = [pred('orders', 'subject:entity object:entity', true), pred('lives', 'subject:entity object:entity', true), pred('zone_of', 'subject:entity object:entity', true), pred('order_zone', 'subject:entity object:entity', true),
    facts.map((f, i) => fact(i + 1, f)).join('\n'),
    '@r_order_zone rule\n  when orders ?o ?c\n  when lives ?c ?g\n  when zone_of ?g ?z\n  then order_zone ?o ?z\n'].join('\n');
  const query = '@q query\n  mode count\n  where order_zone ?o z3\n  select ?o\n';
  let count = 0;
  for (let o = 0; o < O; o++) if (zone(region(cust(o))) === 3) count++;
  return {dir: '50-bulk-three-way-join-count', knowledge, query, readme: 'Bulk relational join. 3,000 orders, 150 customers and 12 regions generated by a fixed formula; a rule joins the three relations (`order_zone`) and the query counts the orders of one zone. A set-at-a-time engine runs the join as one statement; a nested-loop evaluator pays orders times customers. Expected count computed from the generator\'s formula. Feature: bulk joins over thousands of facts, exact count over closed relations.\n',
    expected: {feature: 'Bulk three-way join over 3,000 generated facts, exact count over closed relations', status: 'supported', complete: true, count, requires: ['rules', 'count']}};
}

function aggregateLarge() {
  const P = 4000, D = 8;
  const dept = i => (i < 2500 ? 0 : 1 + ((i - 2500) % (D - 1)));
  const pay = i => 30000 + ((i * 37) % 5000) * 3 + dept(i) * 1000;
  const sums = Array(D).fill(0), n = Array(D).fill(0), mx = Array(D).fill(-Infinity);
  const facts = [];
  for (let i = 0; i < P; i++) { facts.push(`salary p${i} d${dept(i)} ${pay(i)}`); sums[dept(i)] += pay(i); n[dept(i)]++; mx[dept(i)] = Math.max(mx[dept(i)], pay(i)); }
  const knowledge = [pred('salary', 'subject:entity topic:entity object:integer', true), pred('dept_payroll', 'subject:entity object:integer'), pred('dept_size', 'subject:entity object:integer'), pred('top_salary', 'subject:entity object:integer'),
    pred('avg_salary', 'subject:entity object:integer'), pred('gap', 'subject:entity object:integer'),
    facts.map((f, i) => fact(i + 1, f)).join('\n'),
    '@payroll aggregate\n  over salary ?p ?d ?s\n  group ?d\n  sum ?s as ?t\n  yields dept_payroll ?d ?t\n',
    '@headcount aggregate\n  over salary ?p ?d ?s\n  group ?d\n  count as ?n\n  yields dept_size ?d ?n\n',
    '@best aggregate\n  over salary ?p ?d ?s\n  group ?d\n  max ?s as ?m\n  yields top_salary ?d ?m\n',
    '@r_avg rule\n  when dept_payroll ?d ?t\n  when dept_size ?d ?n\n  when compute ?a ?t whole_divided_by ?n\n  then avg_salary ?d ?a\n',
    '@r_gap rule\n  when top_salary ?d ?m\n  when avg_salary ?d ?a\n  when compute ?g ?m minus ?a\n  then gap ?d ?g\n'].join('\n');
  const query = '@q query\n  where gap ?d ?g\n  select ?d ?g\n';
  const rows = Array.from({length: D}, (_, d) => ({d: `d${d}`, g: mx[d] - Math.trunc(sums[d] / n[d])}));
  return {dir: '51-aggregate-large-group-compute', knowledge, query, readme: 'Aggregates over a large group. 4,000 salaries, 2,500 of them in one department; three aggregates (sum, count, max) group them, and two rules use `compute` (an integer average with division truncating toward zero, then the gap between the maximum and the average). A GROUP BY engine reads the 4,000 rows once per aggregate. Expected rows computed from the generator. Feature: aggregate with set semantics over the distinct bindings, `compute` arithmetic and rounding, over a large group.\n',
    expected: {feature: 'Aggregates over a large group and integer arithmetic (division truncates toward zero)', status: 'supported', complete: true, rows, requires: ['aggregate', 'rules', 'compute_in_rules']}};
}

function deepLinear() {
  const N = 110;
  const facts = [];
  for (let i = 0; i < N; i++) facts.push(`edge n${i} n${i + 1}`);
  for (let i = 0; i < 20; i++) facts.push(`edge m${i} m${i + 1}`); // a second chain that is never reached
  facts.push(`edge n${N} n50`); // a back edge: the closure still stops
  facts.push('start n0');
  const knowledge = [pred('edge', 'source:entity destination:entity', true), pred('start', 'subject:entity', true), pred('visited', 'subject:entity', true),
    facts.map((f, i) => fact(i + 1, f)).join('\n'),
    '@r_start rule\n  when start ?x\n  then visited ?x\n',
    '@r_step rule\n  when visited ?x\n  when edge ?x ?y\n  then visited ?y\n'].join('\n');
  const query = '@q query\n  where visited ?t\n  select ?t\n';
  const rows = Array.from({length: N + 1}, (_, i) => ({t: `n${i}`}));
  return {dir: '52-linear-recursion-chain-depth', knowledge, query, readme: 'Linear recursion over a chain of 110 edges (the derivation is 110 rounds deep) with a back edge that makes a cycle and a second chain the walk never reaches. A recursive CTE runs the whole walk as one statement and a UNION keeps the cycle finite; the unit tests of sql-sqlite run the same program at depth 1,000 and compare with the oracle at smaller sizes. Expected rows computed from the generator. Feature: linear recursion, depth, cycle safety.\n',
    expected: {feature: 'Linear recursion 110 rounds deep on a cyclic chain', status: 'supported', complete: true, rows, requires: ['rules', 'recursion']}};
}

function nonlinear() {
  const N = 30;
  const facts = [];
  for (let i = 0; i < N; i++) facts.push(`edge n${i} n${i + 1}`);
  const knowledge = [pred('edge', 'source:entity destination:entity', true), pred('path', 'source:entity destination:entity', true),
    facts.map((f, i) => fact(i + 1, f)).join('\n'),
    '@r_base rule\n  when edge ?x ?y\n  then path ?x ?y\n',
    '@r_join rule\n  when path ?x ?y\n  when path ?y ?z\n  then path ?x ?z\n'].join('\n');
  const query = '@q query\n  mode count\n  where path ?x ?y\n  select ?x ?y\n';
  return {dir: '53-nonlinear-recursion-closure', knowledge, query, readme: 'Nonlinear recursion: the transitive closure written with two recursive atoms (`path` joined with `path`) over a chain of 30 edges. A recursive CTE cannot express it (the recursive table may appear once), so sql-sqlite lowers it to a semi-naive loop of SQL statements; the closure doubles its path length each round. Expected count (30 + 29 + ... + 1 pairs) computed from the chain. Feature: nonlinear recursion, exact count of a closed derived relation.\n',
    expected: {feature: 'Nonlinear recursion (two recursive atoms): the closure of a chain', status: 'supported', complete: true, count: (N * (N + 1)) / 2, requires: ['rules', 'recursion', 'count']}};
}

function policy() {
  const U = 1600, ROLES = 16, RES = 4;
  const facts = [];
  for (let u = 0; u < U; u++) facts.push(`member u${u} r${u % ROLES}`);
  for (let r = 0; r < ROLES; r++) for (let s = 0; s < RES; s++) facts.push(`grant r${r} s${s}`);
  let denied = 0;
  for (let u = 0; u < U; u += 7) { facts.push(`denied u${u} s0`); denied++; }
  const knowledge = [pred('member', 'subject:entity object:entity', true), pred('grant', 'subject:entity object:entity', true), pred('denied', 'subject:entity object:entity', true), pred('can', 'subject:entity object:entity', true),
    facts.map((f, i) => fact(i + 1, f)).join('\n'),
    '@r_can rule\n  when member ?u ?r\n  when grant ?r ?s\n  when absent denied ?u ?s\n  then can ?u ?s\n'].join('\n');
  const query = '@q query\n  mode count\n  where can ?u ?s\n  select ?u ?s\n';
  return {dir: '54-policy-absent-bulk-count', knowledge, query, readme: 'Closed-world policy over thousands of facts: 1,600 members, 16 roles with four grants each and 229 denials. The rule joins membership and grants and keeps a pair only when `absent denied`; the query counts the permitted pairs. The engine runs the stratified negation as one NOT EXISTS over the finished `denied` relation. Expected count = 1,600 x 4 minus the denied pairs, from the generator. Feature: stratified negation as failure over a bulk join, exact count.\n',
    expected: {feature: 'Stratified negation as failure (absent) over a 6,400-row bulk join', status: 'supported', complete: true, count: U * RES - denied, requires: ['rules', 'naf', 'closed_world', 'count']}};
}

export const cases = () => [bulkJoin(), aggregateLarge(), deepLinear(), nonlinear(), policy()];

function files(c) {
  return {'knowledge.sop': c.knowledge, 'query.sop': c.query, 'expected.json': json(c.expected), 'README.md': c.readme};
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check');
  let bad = 0;
  for (const c of cases()) {
    const dir = path.join(casesRoot, c.dir);
    if (!check) fs.mkdirSync(dir, {recursive: true});
    for (const [name, text] of Object.entries(files(c))) {
      const file = path.join(dir, name);
      if (check) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.log('differs: ' + path.relative(process.cwd(), file)); bad++; } } else fs.writeFileSync(file, text);
    }
  }
  console.log(check ? (bad ? `${bad} file(s) differ` : 'cases match the generator') : 'cases 50 to 54 written');
  process.exit(bad ? 1 : 0);
}
